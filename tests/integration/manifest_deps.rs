//! Integration tests for Cargo dependency-declaration extraction and
//! `eg query manifest-deps` (issue #180): every directly-declared Cargo dependency
//! becomes a deterministic, citable graph fact — name, kind, declared
//! requirement, resolved locked version, declaring package, and manifest
//! handle — derived locally and read-only, never via `cargo metadata`.

#![allow(missing_docs)]

use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

use aletheia_egregore::scan_repository_at_with_override;
use assert_cmd::Command;
use serde_json::Value;

const FIXED_TIME: &str = "2026-07-01T00:00:00Z";

fn egregore() -> Command {
    Command::cargo_bin("egregore").expect("binary should be built")
}

// ---------------------------------------------------------------------------
// Fixture: a two-member workspace with a committed Cargo.lock
// ---------------------------------------------------------------------------

/// Virtual workspace root: no `[package]`, no dependency tables — must
/// produce zero dependency facts and zero diagnostics.
const ROOT_MANIFEST: &str = r#"[workspace]
members = ["crates/pkg-a", "crates/local-b"]
"#;

/// First member: all three dependency tables, a path dependency without a
/// version requirement, a dependency missing from the lockfile, and a
/// dependency locked at two different versions.
const PKG_A_MANIFEST: &str = r#"[package]
name = "pkg-a"
version = "0.1.0"

[dependencies]
serde = "1.0.228"
local-b = { path = "../local-b" }
ghost = "0.9"
dupes = "1"

[dev-dependencies]
tempfile = "3"

[build-dependencies]
cc = { version = "1.0", features = ["parallel"] }
"#;

/// Second member: one normal dependency shared with pkg-a.
const LOCAL_B_MANIFEST: &str = r#"[package]
name = "local-b"
version = "0.1.0"

[dependencies]
serde = "1.0.228"
"#;

/// Committed lockfile: `serde`, `tempfile`, `cc`, and `local-b` resolve to a
/// single version; `dupes` is locked at two versions (ambiguous); `ghost`
/// is absent entirely.
const CARGO_LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "cc"
version = "1.0.100"

[[package]]
name = "dupes"
version = "1.0.0"

[[package]]
name = "dupes"
version = "2.0.3"

[[package]]
name = "local-b"
version = "0.1.0"

[[package]]
name = "pkg-a"
version = "0.1.0"

[[package]]
name = "serde"
version = "1.0.228"

[[package]]
name = "tempfile"
version = "3.27.0"
"#;

fn write_fixture(dir: &Path) {
    fs::create_dir_all(dir.join("crates/pkg-a/src")).expect("pkg-a dir");
    fs::create_dir_all(dir.join("crates/local-b/src")).expect("local-b dir");
    fs::write(dir.join("Cargo.toml"), ROOT_MANIFEST).expect("root manifest");
    fs::write(dir.join("Cargo.lock"), CARGO_LOCK).expect("lockfile");
    fs::write(dir.join("crates/pkg-a/Cargo.toml"), PKG_A_MANIFEST).expect("pkg-a manifest");
    fs::write(dir.join("crates/local-b/Cargo.toml"), LOCAL_B_MANIFEST).expect("local-b manifest");
    fs::write(dir.join("crates/pkg-a/src/lib.rs"), "pub fn a() {}\n").expect("pkg-a lib");
    fs::write(dir.join("crates/local-b/src/lib.rs"), "pub fn b() {}\n").expect("local-b lib");
}

/// Scans the workspace fixture and writes the JSONL graph. Returns
/// (`TempDir`, graph path). The graph is written *outside* the fixture tree
/// so read-only assertions can hash the fixture exactly.
fn fixture_graph() -> (tempfile::TempDir, PathBuf) {
    let temp = tempfile::tempdir().expect("temp dir");
    let repo = temp.path().join("repo");
    fs::create_dir_all(&repo).expect("repo dir");
    write_fixture(&repo);
    let jsonl = scan_repository_at_with_override(&repo, FIXED_TIME, Some("deps-fixture"))
        .expect("fixture should scan")
        .to_jsonl()
        .expect("graph should serialize");
    let graph = temp.path().join("graph.jsonl");
    fs::write(&graph, jsonl).expect("write graph");
    (temp, graph)
}

/// Parses every `DependencyDeclaration` node record from a graph JSONL.
fn dependency_nodes(graph: &Path) -> Vec<Value> {
    fs::read_to_string(graph)
        .expect("graph must be readable")
        .lines()
        .map(|line| serde_json::from_str::<Value>(line).expect("valid record JSON"))
        .filter(|record| record["kind"] == "DependencyDeclaration")
        .collect()
}

fn run_query_deps(graph: &Path, extra: &[&str]) -> Value {
    let output = egregore()
        .args(["query", "manifest-deps", "--graph"])
        .arg(graph)
        .args(extra)
        .assert()
        .success()
        .get_output()
        .stdout
        .clone();
    serde_json::from_str(std::str::from_utf8(&output).expect("utf8").trim())
        .expect("stdout must be valid JSON")
}

fn declaration<'a>(parsed: &'a Value, package: &str, kind: &str, name: &str) -> &'a Value {
    parsed["declarations"]
        .as_array()
        .expect("declarations array")
        .iter()
        .find(|d| {
            d["declaring_package"] == package && d["dependency_kind"] == kind && d["name"] == name
        })
        .unwrap_or_else(|| panic!("missing declaration ({package}, {kind}, {name})"))
}

// ---------------------------------------------------------------------------
// AC1: one deterministic fact per (declaring package, name, kind)
// ---------------------------------------------------------------------------

#[test]
fn scan_captures_one_fact_per_declared_dependency() {
    let (_temp, graph) = fixture_graph();
    let nodes = dependency_nodes(&graph);

    let mut keys: Vec<(String, String, String)> = nodes
        .iter()
        .map(|n| {
            (
                n["dependency"]["declaring_package"]
                    .as_str()
                    .expect("declaring_package")
                    .to_owned(),
                n["dependency"]["dependency_kind"]
                    .as_str()
                    .expect("dependency_kind")
                    .to_owned(),
                n["name"].as_str().expect("name").to_owned(),
            )
        })
        .collect();
    keys.sort();
    let expected: Vec<(String, String, String)> = [
        ("local-b", "normal", "serde"),
        ("pkg-a", "build", "cc"),
        ("pkg-a", "dev", "tempfile"),
        ("pkg-a", "normal", "dupes"),
        ("pkg-a", "normal", "ghost"),
        ("pkg-a", "normal", "local-b"),
        ("pkg-a", "normal", "serde"),
    ]
    .iter()
    .map(|(p, k, n)| ((*p).to_owned(), (*k).to_owned(), (*n).to_owned()))
    .collect();
    assert_eq!(keys, expected, "exactly one fact per declaration");
}

// ---------------------------------------------------------------------------
// AC2: each fact carries name, kind, requirement, resolved version,
//       declaring package, and the manifest handle
// ---------------------------------------------------------------------------

#[test]
fn facts_carry_requirement_resolution_and_manifest_handle() {
    let (_temp, graph) = fixture_graph();
    let nodes = dependency_nodes(&graph);

    let serde_a = nodes
        .iter()
        .find(|n| n["name"] == "serde" && n["dependency"]["declaring_package"] == "pkg-a")
        .expect("pkg-a serde fact");
    assert_eq!(serde_a["repo_relative_path"], "crates/pkg-a/Cargo.toml");
    assert_eq!(serde_a["dependency"]["dependency_kind"], "normal");
    assert_eq!(serde_a["dependency"]["declared_requirement"], "1.0.228");
    assert_eq!(serde_a["dependency"]["resolved_version"], "1.0.228");
    assert_eq!(serde_a["dependency"]["resolution"], "locked");
    assert!(
        serde_a["id"]
            .as_str()
            .expect("stable record id")
            .starts_with("codegraph:v"),
        "dependency facts carry stable codegraph record IDs"
    );

    // Inline-table declaration: requirement is the `version` key as written.
    let cc = nodes
        .iter()
        .find(|n| n["name"] == "cc")
        .expect("cc build-dependency fact");
    assert_eq!(cc["dependency"]["dependency_kind"], "build");
    assert_eq!(cc["dependency"]["declared_requirement"], "1.0");
    assert_eq!(cc["dependency"]["resolved_version"], "1.0.100");

    // Path dependency without a version key: no fabricated requirement.
    let local_b = nodes
        .iter()
        .find(|n| n["name"] == "local-b" && n["kind"] == "DependencyDeclaration")
        .expect("local-b path-dependency fact");
    assert!(
        local_b["dependency"]["declared_requirement"].is_null(),
        "path dependency without a version key must not fabricate a requirement"
    );
    assert_eq!(local_b["dependency"]["resolved_version"], "0.1.0");
    assert_eq!(local_b["dependency"]["resolution"], "locked");
}

