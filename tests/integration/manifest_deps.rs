// ---------------------------------------------------------------------------
// Robustness: a malformed manifest degrades to a diagnostic, never a panic
// ---------------------------------------------------------------------------

#[test]
fn malformed_manifest_yields_diagnostic_not_failure() {
    let temp = tempfile::tempdir().expect("temp dir");
    let repo = temp.path().join("repo");
    fs::create_dir_all(&repo).expect("repo dir");
    write_fixture(&repo);
    fs::write(
        repo.join("crates/pkg-a/Cargo.toml"),
        "[package\nname = broken",
    )
    .expect("break the manifest");

    let jsonl = scan_repository_at_with_override(&repo, FIXED_TIME, Some("deps-fixture"))
        .expect("scan must not fail on a malformed manifest")
        .to_jsonl()
        .expect("graph should serialize");
    let graph = temp.path().join("graph.jsonl");
    fs::write(&graph, jsonl).expect("write graph");

    let nodes = dependency_nodes(&graph);
    assert!(
        nodes
            .iter()
            .all(|n| n["dependency"]["declaring_package"] != "pkg-a"),
        "no facts are invented for an unparseable manifest"
    );
    // local-b still contributes its declaration.
    assert!(nodes.iter().any(|n| n["name"] == "serde"));

    let raw = fs::read_to_string(&graph).expect("graph text");
    let diagnostic = raw.lines().any(|line| {
        let record: Value = serde_json::from_str(line).expect("record JSON");
        record["kind"] == "Diagnostic" && record["repo_relative_path"] == "crates/pkg-a/Cargo.toml"
    });
    assert!(
        diagnostic,
        "the malformed manifest is reported as a Diagnostic"
    );
}

// ---------------------------------------------------------------------------
// Embedded round-trip: `eg query manifest-deps --data-dir` equals the JSONL answer
// ---------------------------------------------------------------------------

#[cfg(feature = "embedded-aletheiadb")]
#[test]
fn query_deps_round_trips_through_the_embedded_store() {
    let (temp, graph) = fixture_graph();
    let data_dir = temp.path().join("store");
    egregore()
        .arg("ingest")
        .arg(&graph)
        .args(["--adapter", "embedded", "--data-dir"])
        .arg(&data_dir)
        .assert()
        .success();

    let from_graph = run_query_deps(&graph, &[]);
    let output = egregore()
        .args(["query", "manifest-deps", "--data-dir"])
        .arg(&data_dir)
        .assert()
        .success()
        .get_output()
        .stdout
        .clone();
    let from_store: Value =
        serde_json::from_str(std::str::from_utf8(&output).expect("utf8").trim())
            .expect("store answer must be valid JSON");
    assert_eq!(
        from_store["declarations"], from_graph["declarations"],
        "embedded store answer must match the JSONL answer"
    );
}
