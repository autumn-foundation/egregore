// ---------------------------------------------------------------------------
// AC5: strictly read-only — no records, indexes, or working-tree mutation
// ---------------------------------------------------------------------------

fn tree_snapshot(root: &Path) -> BTreeMap<String, String> {
    fn walk(root: &Path, dir: &Path, out: &mut BTreeMap<String, String>) {
        for entry in fs::read_dir(dir).expect("read_dir") {
            let entry = entry.expect("dir entry");
            let path = entry.path();
            if path.is_dir() {
                walk(root, &path, out);
            } else {
                let rel = path
                    .strip_prefix(root)
                    .expect("under root")
                    .to_string_lossy()
                    .replace('\\', "/");
                let bytes = fs::read(&path).expect("file bytes");
                out.insert(rel, blake3::hash(&bytes).to_hex().to_string());
            }
        }
    }
    let mut out = BTreeMap::new();
    walk(root, root, &mut out);
    out
}

#[test]
fn scan_and_query_mutate_nothing_in_the_fixture_tree() {
    let temp = tempfile::tempdir().expect("temp dir");
    let repo = temp.path().join("repo");
    fs::create_dir_all(&repo).expect("repo dir");
    write_fixture(&repo);
    let before = tree_snapshot(&repo);

    let graph = temp.path().join("graph.jsonl");
    egregore()
        .arg("scan")
        .arg(&repo)
        .arg("--out")
        .arg(&graph)
        .arg("--repo-id-override")
        .arg("deps-fixture")
        .assert()
        .success();
    let _ = run_query_deps(&graph, &[]);
    let _ = run_query_deps(&graph, &["--name", "serde"]);

    let after = tree_snapshot(&repo);
    assert_eq!(before, after, "fixture tree must be byte-identical");
}

